"""Deterministic behavioural signals for the reference portfolio.

The reference build deliberately produces the same event shape as the signal
ingestion boundary will consume later, while keeping this evaluation package
independent of the application's persistence layer.  Events are generated by
index rather than stored in a list.  A full reference build contains
12,775,000 events, so this sequence is both iterable and memory bounded.
"""

